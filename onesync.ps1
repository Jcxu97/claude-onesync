#Requires -Version 7.0
<#
.SYNOPSIS
  Keep Claude Code config and memory the same on every machine through one private git repo.

.DESCRIPTION
  One round does this:
    1. Pull the repo.
    2. Find files that you deleted on this machine, and remove them from the repo.
    3. Find files that other machines deleted, and move the local copies to the trash.
    4. Copy each changed file in the direction of the newer version.
    5. Copy shared memory into every project memory folder.
    6. Rebuild MEMORY.md indexes.
    7. Commit and push.

.EXAMPLE
  pwsh ./onesync.ps1 sync
  pwsh ./onesync.ps1 sync -DryRun
  pwsh ./onesync.ps1 install-schedule
#>
[CmdletBinding()]
param(
  [Parameter(Position = 0)]
  [ValidateSet('sync', 'status', 'install-hook', 'install-schedule', 'uninstall-schedule')]
  [string]$Command = 'sync',
  [string]$Repo = $PSScriptRoot,
  [string]$ClaudeHome = (Join-Path $HOME '.claude'),
  [int]$MaxDelete = 30,
  [int]$EveryMinutes = 20,
  [switch]$AllowMassDelete,
  [switch]$AllowPublicRepo,
  [switch]$NoPush,
  [switch]$AllowSecrets,
  [switch]$DryRun,
  [switch]$Quiet
)
if ($Command -eq 'status') { $DryRun = $true }
$ErrorActionPreference = 'Stop'

# Top-level items under ~/.claude that every machine shares. Machine-only files
# (CLAUDE.local.md, settings.local.json, .credentials.json, transcripts) are never read.
$SharedItems = @('CLAUDE.md', 'settings.json', 'agents', 'commands', 'hooks', 'skills', 'output-styles')
# Memory files with one of these frontmatter types go to memory/_shared and reach every project.
$SharedMemoryTypes = @('feedback', 'user')

$Machine   = [Environment]::MachineName
$Projects  = Join-Path $ClaudeHome 'projects'
$StateFile = Join-Path $ClaudeHome '.onesync-state.json'
$LogFile   = Join-Path $ClaudeHome '.onesync.log'
$Stamp     = Get-Date -Format 'yyyyMMdd-HHmmss'
$Trash     = Join-Path $ClaudeHome ".onesync-trash/$Stamp"
$MarkStart = '<!-- ONESYNC-SHARED-START: generated by onesync from memory/_shared. Do not edit. -->'
$MarkEnd   = '<!-- ONESYNC-SHARED-END -->'

function Write-Log([string]$Message, [string]$Color = 'Gray') {
  if (-not $Quiet) { Write-Host $Message -ForegroundColor $Color }
  if (-not $DryRun) { Add-Content -LiteralPath $LogFile -Value "[$(Get-Date -Format s)] $Message" -Encoding utf8 }
}

function Invoke-Git([string[]]$GitArgs, [switch]$AllowFail) {
  $out = & git -C $Repo -c core.quotepath=off @GitArgs 2>&1
  if ($LASTEXITCODE -and -not $AllowFail) { throw "git $($GitArgs -join ' ') failed:`n$($out -join "`n")" }
  [pscustomobject]@{ Code = $LASTEXITCODE; Lines = @($out | ForEach-Object { "$_" }) }
}

function ConvertTo-Key([string]$Root, [string]$Path) {
  [IO.Path]::GetRelativePath($Root, $Path).Replace('\', '/')
}

# A folder that is a symlink, a junction or a git clone belongs to some other tool.
# Never read, write or delete inside it.
function Test-Foreign([string]$Path, [string]$Root) {
  $rootFull = [IO.Path]::GetFullPath($Root).TrimEnd('\', '/')
  $dir = Split-Path ([IO.Path]::GetFullPath($Path)) -Parent
  while ($dir -and $dir.Length -gt $rootFull.Length) {
    $item = Get-Item -LiteralPath $dir -Force -ErrorAction SilentlyContinue
    if ($item) {
      if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { return $true }
      if (Test-Path -LiteralPath (Join-Path $dir '.git')) { return $true }
    }
    $dir = Split-Path $dir -Parent
  }
  $false
}

function Test-SameBytes([string]$A, [string]$B) {
  $fa = Get-Item -LiteralPath $A; $fb = Get-Item -LiteralPath $B
  if ($fa.Length -ne $fb.Length) { return $false }
  [Linq.Enumerable]::SequenceEqual([IO.File]::ReadAllBytes($A), [IO.File]::ReadAllBytes($B))
}

function Get-Frontmatter([string]$Path) {
  $meta = @{}
  $lines = @(Get-Content -LiteralPath $Path -TotalCount 40 -Encoding utf8)
  if (-not $lines.Count -or $lines[0].Trim() -ne '---') { return $meta }
  foreach ($l in $lines[1..($lines.Count - 1)]) {
    if ($l.Trim() -eq '---') { break }
    if ($l -match '^\s*(name|description|type)\s*:\s*(.*)$') { $meta[$Matches[1]] = $Matches[2].Trim().Trim('"', "'") }
  }
  $meta
}

function Copy-File([string]$From, [string]$To) {
  if ($DryRun) { return }
  $dir = Split-Path $To -Parent
  if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
  Copy-Item -LiteralPath $From -Destination $To -Force
}

function Move-ToTrash([string]$Path) {
  if ($DryRun) { return }
  $to = Join-Path $Trash (ConvertTo-Key $ClaudeHome $Path)
  New-Item -ItemType Directory -Force -Path (Split-Path $to -Parent) | Out-Null
  Move-Item -LiteralPath $Path -Destination $to -Force
}

# One pass over git history. For each path: the status and time of its newest change.
# Git does not keep file times, so the commit time is the only true "published at" time.
function Get-History {
  $map = @{}; $when = $null
  foreach ($l in (Invoke-Git @('log', '--no-renames', '--name-status', '--format=@%cI', '--', 'claude', 'memory') -AllowFail).Lines) {
    if ($l.StartsWith('@')) { $when = [DateTimeOffset]::Parse($l.Substring(1)).UtcDateTime; continue }
    $parts = $l -split "`t", 2
    if ($parts.Count -lt 2) { continue }
    if (-not $map.ContainsKey($parts[1])) { $map[$parts[1]] = [pscustomobject]@{ Status = $parts[0].Substring(0, 1); Time = $when } }
  }
  $map
}

$IgnoreRe = '(^|/)(__pycache__|node_modules|\.venv|\.cache|\.DS_Store)(/|$)|\.pyc$'
# Extra patterns, one per line, matched against paths like "skills/big-skill/*".
$IgnoreFile = Join-Path $Repo '.onesyncignore'
$IgnoreGlobs = if (Test-Path -LiteralPath $IgnoreFile) {
  @(Get-Content -LiteralPath $IgnoreFile | ForEach-Object { $_.Trim() } | Where-Object { $_ -and -not $_.StartsWith('#') })
} else { @() }
function Test-Ignored([string]$Key) {
  if ($Key -match $IgnoreRe) { return $true }
  foreach ($g in $IgnoreGlobs) { if ($Key -like $g) { return $true } }
  $false
}

# Text that looks like a credential. Files with a match stay on this machine.
$SecretRe = 'sk-ant-[A-Za-z0-9_-]{20,}|\bsk-[A-Za-z0-9]{32,}|\bgh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|\bAKIA[0-9A-Z]{16}\b|\bxox[abprs]-[A-Za-z0-9-]{10,}|\bAIza[0-9A-Za-z_-]{35}|-----BEGIN [A-Z ]*PRIVATE KEY-----'
function Test-HasSecret([string]$Path) {
  if ((Get-Item -LiteralPath $Path).Length -gt 2MB) { return $false }
  try { (Get-Content -LiteralPath $Path -Raw -ErrorAction Stop) -match $SecretRe } catch { $false }
}
$ForeignCache = @{}
function Test-ForeignCached([string]$Path, [string]$Root) {
  $dir = Split-Path $Path -Parent
  if (-not $ForeignCache.ContainsKey($dir)) { $ForeignCache[$dir] = Test-Foreign $Path $Root }
  $ForeignCache[$dir]
}

function Get-Namespaces {
  $names = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
  foreach ($d in (Get-ChildItem -LiteralPath $Projects -Directory -Force -ErrorAction SilentlyContinue)) { [void]$names.Add($d.Name) }
  foreach ($d in (Get-ChildItem -LiteralPath (Join-Path $Repo 'memory') -Directory -ErrorAction SilentlyContinue)) {
    if ($d.Name -ne '_shared') { [void]$names.Add($d.Name) }
  }
  @($names | Sort-Object)
}

# Local files in scope. Key = path under ~/.claude with forward slashes.
function Get-LocalFiles {
  $files = @{}
  foreach ($item in $SharedItems) {
    $p = Join-Path $ClaudeHome $item
    if (Test-Path -LiteralPath $p -PathType Leaf) { $files[$item] = $p; continue }
    if (-not (Test-Path -LiteralPath $p -PathType Container)) { continue }
    if ((Get-Item -LiteralPath $p -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }
    foreach ($f in (Get-ChildItem -LiteralPath $p -Recurse -File -Force -ErrorAction SilentlyContinue)) {
      $key = ConvertTo-Key $ClaudeHome $f.FullName
      if ((Test-Ignored $key) -or (Test-ForeignCached $f.FullName $ClaudeHome)) { continue }
      $files[$key] = $f.FullName
    }
  }
  foreach ($d in (Get-ChildItem -LiteralPath $Projects -Directory -Force -ErrorAction SilentlyContinue)) {
    $mem = Join-Path $d.FullName 'memory'
    if (-not (Test-Path -LiteralPath $mem -PathType Container)) { continue }
    if ((Get-Item -LiteralPath $mem -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }
    foreach ($f in (Get-ChildItem -LiteralPath $mem -Recurse -File -Force -ErrorAction SilentlyContinue)) {
      if ($f.Name -eq 'MEMORY.md' -and $f.DirectoryName -eq $mem) { continue }
      $key = ConvertTo-Key $ClaudeHome $f.FullName
      if ((Test-Ignored $key) -or (Test-ForeignCached $f.FullName $mem)) { continue }
      $files[$key] = $f.FullName
    }
  }
  $files
}

# Repo files in scope. Key = repo path with forward slashes.
function Get-RepoFiles {
  $files = @{}
  foreach ($top in 'claude', 'memory') {
    $p = Join-Path $Repo $top
    foreach ($f in (Get-ChildItem -LiteralPath $p -Recurse -File -Force -ErrorAction SilentlyContinue)) {
      $rel = ConvertTo-Key $Repo $f.FullName
      if ($f.Name -eq '.gitkeep' -or $rel -match '^memory/[^/]+/MEMORY\.md$') { continue }
      if ($rel.StartsWith('claude/') -and (Test-Ignored $rel.Substring(7))) { continue }
      $files[$rel] = $f.FullName
    }
  }
  $files
}

function Get-RepoRel([string]$Key, $Shared, $RepoFiles, [string]$LocalPath) {
  if ($Key -notmatch '^projects/([^/]+)/memory/(.+)$') { return "claude/$Key" }
  $ns = $Matches[1]; $rest = $Matches[2]
  if ($rest.Contains('/')) { return "memory/$ns/$rest" }
  if ($Shared.Contains($rest)) { return "memory/_shared/$rest" }
  $nsRel = "memory/$ns/$rest"
  if (-not $RepoFiles.ContainsKey($nsRel) -and $LocalPath -and $rest.EndsWith('.md') -and
      (Get-Frontmatter $LocalPath).type -in $SharedMemoryTypes) { return "memory/_shared/$rest" }
  $nsRel
}

function Get-LocalKeys([string]$Rel, $Namespaces) {
  if ($Rel -match '^memory/_shared/(.+)$') { $f = $Matches[1]; return @($Namespaces | ForEach-Object { "projects/$_/memory/$f" }) }
  if ($Rel -match '^memory/([^/]+)/(.+)$') { return @("projects/$($Matches[1])/memory/$($Matches[2])") }
  if ($Rel -match '^claude/(.+)$') { return @($Matches[1]) }
  @()
}

function Get-SharedNames {
  $set = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
  foreach ($f in (Get-ChildItem -LiteralPath (Join-Path $Repo 'memory/_shared') -File -ErrorAction SilentlyContinue)) {
    if ($f.Name -ne '.gitkeep') { [void]$set.Add($f.Name) }
  }
  Write-Output -NoEnumerate $set
}

function Read-State {
  $set = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
  if (Test-Path -LiteralPath $StateFile) {
    foreach ($k in (Get-Content -LiteralPath $StateFile -Raw | ConvertFrom-Json).files) { [void]$set.Add($k) }
  }
  Write-Output -NoEnumerate $set
}

function Get-Mtime([string]$Path) { (Get-Item -LiteralPath $Path -Force).LastWriteTimeUtc }

function Get-SyncPlan {
  $hist      = Get-History
  $prev      = Read-State
  $repoFiles = Get-RepoFiles
  $shared    = Get-SharedNames
  $local     = Get-LocalFiles
  $plan = [pscustomobject]@{
    DeleteInRepo = New-Object 'System.Collections.Generic.HashSet[string]'
    Trash        = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
    ToRepo       = @{}   # repo rel -> local path
    ToLocal      = @{}   # local key -> repo path
  }

  # 1. Deleted on this machine: synced last round, gone now. A project folder that is
  #    gone as a whole is not a delete (Claude Code can clean up old project folders).
  foreach ($k in $prev) {
    if ($local.ContainsKey($k)) { continue }
    if ($k -match '^projects/([^/]+)/memory/' -and -not (Test-Path -LiteralPath (Join-Path $Projects "$($Matches[1])/memory"))) { continue }
    $rel = Get-RepoRel $k $shared $repoFiles $null
    if ($repoFiles.ContainsKey($rel)) { [void]$plan.DeleteInRepo.Add($rel) }
  }
  $namespaces = Get-Namespaces
  foreach ($rel in $plan.DeleteInRepo) {
    if ($rel -notlike 'memory/_shared/*') { continue }
    foreach ($k in (Get-LocalKeys $rel $namespaces)) { if ($local.ContainsKey($k)) { [void]$plan.Trash.Add($local[$k]) } }
  }

  # 2. Every local file, grouped by repo path (one shared memory has one copy per project).
  $byRel = @{}
  foreach ($k in $local.Keys) {
    $rel = Get-RepoRel $k $shared $repoFiles $local[$k]
    if ($plan.DeleteInRepo.Contains($rel)) { continue }
    if (-not $byRel.ContainsKey($rel)) { $byRel[$rel] = [Collections.Generic.List[string]]::new() }
    $byRel[$rel].Add($k)
  }
  foreach ($rel in $byRel.Keys) {
    $keys = $byRel[$rel]
    $h = $hist[$rel]
    if (-not $repoFiles.ContainsKey($rel)) {
      # Not in the repo. If the repo deleted it after this copy was last changed, the copy is stale.
      $live = @()
      foreach ($k in $keys) {
        if ($h -and $h.Status -eq 'D' -and (Get-Mtime $local[$k]) -le $h.Time) { [void]$plan.Trash.Add($local[$k]) }
        else { $live += $k }
      }
      if ($live) { $plan.ToRepo[$rel] = $local[($live | Sort-Object { Get-Mtime $local[$_] } -Descending | Select-Object -First 1)] }
      continue
    }
    $repoPath = $repoFiles[$rel]
    $published = if ($h) { $h.Time } else { [datetime]::MinValue }
    $differ = @($keys | Where-Object { -not (Test-SameBytes $local[$_] $repoPath) })
    if (-not $differ) { continue }
    $newest = $differ | Sort-Object { Get-Mtime $local[$_] } -Descending | Select-Object -First 1
    if ((Get-Mtime $local[$newest]) -gt $published) { $plan.ToRepo[$rel] = $local[$newest] }
    else { foreach ($k in $differ) { $plan.ToLocal[$k] = $repoPath } }
  }

  # 3. Repo files that this machine does not have yet.
  foreach ($rel in $repoFiles.Keys) {
    if ($plan.DeleteInRepo.Contains($rel)) { continue }
    foreach ($k in (Get-LocalKeys $rel $namespaces)) {
      if (-not $local.ContainsKey($k) -and -not $prev.Contains($k)) { $plan.ToLocal[$k] = $repoFiles[$rel] }
    }
  }
  $plan
}

function Invoke-Plan($Plan) {
  $deletes = $Plan.DeleteInRepo.Count + $Plan.Trash.Count
  if ($deletes -gt $MaxDelete -and -not $AllowMassDelete) {
    $Plan.DeleteInRepo + $Plan.Trash | Select-Object -First 15 | ForEach-Object { Write-Log "  would delete $_" 'DarkGray' }
    throw "This round wants to delete $deletes files (limit $MaxDelete). Nothing was changed. Check the list, then run again with -AllowMassDelete."
  }
  foreach ($p in $Plan.Trash) { Write-Log "  trash   $(ConvertTo-Key $ClaudeHome $p)" 'Yellow'; Move-ToTrash $p }
  foreach ($rel in $Plan.DeleteInRepo) {
    Write-Log "  delete  $rel" 'Yellow'
    if (-not $DryRun) { Remove-Item -LiteralPath (Join-Path $Repo $rel) -Force }
  }
  foreach ($rel in @($Plan.ToRepo.Keys)) {
    if (-not $AllowSecrets -and (Test-HasSecret $Plan.ToRepo[$rel])) {
      Write-Log "  skip    $rel (looks like it holds an API key; move the key to an environment variable or settings.local.json)" 'Red'
      $Plan.ToRepo.Remove($rel)
      continue
    }
    Write-Log "  upload  $rel" 'Cyan'; Copy-File $Plan.ToRepo[$rel] (Join-Path $Repo $rel)
  }
  foreach ($k in $Plan.ToLocal.Keys) {
    $to = Join-Path $ClaudeHome $k
    Write-Log "  update  $k" 'Green'
    # The replaced local version goes to the trash, so a lost conflict can still be recovered.
    if ((Test-Path -LiteralPath $to) -and -not $DryRun) {
      $keep = Join-Path $Trash $k
      New-Item -ItemType Directory -Force -Path (Split-Path $keep -Parent) | Out-Null
      Copy-Item -LiteralPath $to -Destination $keep -Force
    }
    Copy-File $Plan.ToLocal[$k] $to
  }

  # Shared memory that changed this round goes to every project folder.
  $namespaces = Get-Namespaces
  foreach ($f in (Get-ChildItem -LiteralPath (Join-Path $Repo 'memory/_shared') -File -ErrorAction SilentlyContinue)) {
    if ($f.Name -eq '.gitkeep') { continue }
    foreach ($ns in $namespaces) {
      $to = Join-Path $Projects "$ns/memory/$($f.Name)"
      if (-not (Test-Path -LiteralPath $to) -or -not (Test-SameBytes $f.FullName $to)) { Copy-File $f.FullName $to }
    }
  }
}

$LinkRe = '\]\(([^)]+\.md)\)'
function Get-Link([string]$Line) { if ($Line -match $LinkRe) { $Matches[1] } }

function Get-OwnLines([string]$Path, $Shared) {
  if (-not (Test-Path -LiteralPath $Path)) { return @() }
  $keep = @(); $inBlock = $false
  foreach ($l in (Get-Content -LiteralPath $Path -Encoding utf8)) {
    if ($l -eq $MarkStart) { $inBlock = $true; continue }
    if ($l -eq $MarkEnd) { $inBlock = $false; continue }
    if ($inBlock) { continue }
    $link = Get-Link $l
    if ($link -and $Shared.Contains($link)) { continue }
    $keep += $l
  }
  $keep
}

function Set-TextIfChanged([string]$Path, [string[]]$Lines) {
  $text = ($Lines -join "`n").TrimEnd() + "`n"
  if ((Test-Path -LiteralPath $Path) -and (Get-Content -LiteralPath $Path -Raw -Encoding utf8) -eq $text) { return }
  if ($DryRun) { return }
  New-Item -ItemType Directory -Force -Path (Split-Path $Path -Parent) | Out-Null
  [IO.File]::WriteAllText($Path, $text, [Text.UTF8Encoding]::new($false))
}

# MEMORY.md = this project's own index lines (merged across machines) + a generated block
# for shared memory. Lines that point to a file that no longer exists are dropped.
function Update-Indexes {
  $hist = Get-History
  $shared = Get-SharedNames
  $sharedLines = @(Get-ChildItem -LiteralPath (Join-Path $Repo 'memory/_shared') -File -Filter *.md -ErrorAction SilentlyContinue |
    Sort-Object Name | ForEach-Object {
      $m = Get-Frontmatter $_.FullName
      $title = if ($m.name) { $m.name } else { $_.BaseName }
      if ($m.description) { "- [$title]($($_.Name)) - $($m.description)" } else { "- [$title]($($_.Name))" }
    })
  foreach ($ns in (Get-Namespaces)) {
    $mem = Join-Path $Projects "$ns/memory"
    $localIdx = Join-Path $mem 'MEMORY.md'
    $repoIdx = Join-Path $Repo "memory/$ns/MEMORY.md"
    $localOwn = @(Get-OwnLines $localIdx $shared)
    $repoOwn = @(Get-OwnLines $repoIdx $shared)
    $h = $hist["memory/$ns/MEMORY.md"]
    $published = if ($h) { $h.Time } else { [datetime]::MinValue }
    $preferLocal = (Test-Path -LiteralPath $localIdx) -and (Get-Mtime $localIdx) -gt $published
    if ($preferLocal) { $first = $localOwn; $second = $repoOwn } else { $first = $repoOwn; $second = $localOwn }
    $seen = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
    foreach ($l in $first) { $k = Get-Link $l; if ($k) { [void]$seen.Add($k) } }
    $merged = @($first) + @($second | Where-Object { $k = Get-Link $_; $k -and $seen.Add($k) })
    $merged = @($merged | Where-Object { $k = Get-Link $_; -not $k -or (Test-Path -LiteralPath (Join-Path $mem $k)) })
    $hasOwn = [bool]($merged | Where-Object { $_.Trim() })
    if ($hasOwn) { Set-TextIfChanged $repoIdx $merged }
    elseif ((Test-Path -LiteralPath $repoIdx) -and -not $DryRun) { Remove-Item -LiteralPath $repoIdx -Force }
    if ($hasOwn -or $sharedLines) {
      $out = if ($hasOwn) { $merged + @('') } else { @() }
      if ($sharedLines) { $out += @($MarkStart) + $sharedLines + @($MarkEnd) }
      Set-TextIfChanged $localIdx $out
    }
  }
}

function Save-State {
  if ($DryRun) { return }
  $keys = @((Get-LocalFiles).Keys | Sort-Object)
  [IO.File]::WriteAllText($StateFile, (@{ machine = $Machine; time = (Get-Date -Format o); files = $keys } | ConvertTo-Json -Depth 3), [Text.UTF8Encoding]::new($false))
}

function Test-HasRemote { [bool](Invoke-Git @('remote') -AllowFail).Lines }

# settings.json often holds API keys in "env". A public repo would publish them.
function Assert-PrivateRepo {
  if ($AllowPublicRepo -or -not (Test-HasRemote)) { return }
  if (-not (Get-Command gh -ErrorAction SilentlyContinue)) {
    Write-Log 'Install GitHub CLI (gh) so onesync can check that the repo is private.' 'Yellow'
    return
  }
  $url = ((Invoke-Git @('remote', 'get-url', 'origin') -AllowFail).Lines | Select-Object -First 1)
  $private = (& gh repo view $url --json isPrivate -q .isPrivate 2>$null)
  if ($private -eq 'false') { throw "The repo $url is public. Your settings and memory would be published. Make it private, or run with -AllowPublicRepo." }
}

function Sync-Pull {
  if (-not (Test-HasRemote)) { return }
  # Our side wins a rebase conflict: our commit is the newer change.
  $r = Invoke-Git @('pull', '--rebase', '-X', 'theirs', '--autostash') -AllowFail
  if ($r.Code) {
    Invoke-Git @('rebase', '--abort') -AllowFail | Out-Null
    throw "git pull failed. Fix the repo by hand, then run again:`n$($r.Lines -join "`n")"
  }
}

function Publish {
  if ($DryRun) { return }
  Invoke-Git @('add', '-A', '--', 'claude', 'memory') | Out-Null
  if ((Invoke-Git @('status', '--porcelain', '--', 'claude', 'memory')).Lines) {
    Invoke-Git @('commit', '-q', '-m', "onesync: $Machine $(Get-Date -Format 'yyyy-MM-dd HH:mm')") | Out-Null
    Write-Log 'Committed.' 'Green'
  }
  if ($NoPush -or -not (Test-HasRemote)) { return }
  foreach ($try in 1..3) {
    if (-not (Invoke-Git @('push', '-q') -AllowFail).Code) { Write-Log 'Pushed.' 'Green'; return }
    Sync-Pull
  }
  throw 'git push failed 3 times. The commit is kept and goes out next round.'
}

function Invoke-Sync {
  if (Test-Path -LiteralPath (Join-Path $Repo '.onesync-template')) {
    throw "This is the template repo. Create your own private copy first (see README, step 1), then delete .onesync-template in it."
  }
  if (-not (Test-Path -LiteralPath (Join-Path $Repo '.git'))) { throw "$Repo is not a git repo." }
  if (-not (Test-Path -LiteralPath $ClaudeHome)) { throw "$ClaudeHome does not exist." }
  # The scheduled task and the session-start hook can start at the same time. Only one runs.
  $lock = Join-Path $ClaudeHome '.onesync.lock'
  if ((Test-Path -LiteralPath $lock) -and (Get-Item -LiteralPath $lock).LastWriteTime -gt (Get-Date).AddMinutes(-10)) {
    Write-Log 'Another onesync round is running. Skipped.'
    return
  }
  [IO.File]::WriteAllText($lock, "$PID")
  try {
    Write-Log "== onesync $(if ($DryRun) { '(dry run) ' })on $Machine =="
    Assert-PrivateRepo
    Sync-Pull
    $plan = Get-SyncPlan
    Invoke-Plan $plan
    Update-Indexes
    Save-State
    Publish
    $n = $plan.DeleteInRepo.Count + $plan.Trash.Count + $plan.ToRepo.Count + $plan.ToLocal.Count
    Write-Log "Done. $n file changes."
    # Trash folders older than 30 days are removed.
    Get-ChildItem -LiteralPath (Join-Path $ClaudeHome '.onesync-trash') -Directory -ErrorAction SilentlyContinue |
      Where-Object { $_.LastWriteTime -lt (Get-Date).AddDays(-30) } | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
  } finally {
    Remove-Item -LiteralPath $lock -Force -ErrorAction SilentlyContinue
  }
}

# Adds a SessionStart hook, so each new Claude Code session starts with the newest config.
# The hook script is the same on every machine. The repo path stays in a machine-only file.
function Install-Hook {
  [IO.File]::WriteAllText((Join-Path $ClaudeHome '.onesync-repo'), [IO.Path]::GetFullPath($Repo))
  $hooks = Join-Path $ClaudeHome 'hooks'
  New-Item -ItemType Directory -Force -Path $hooks | Out-Null
  Copy-Item -LiteralPath (Join-Path $Repo 'tools/onesync-session.ps1') -Destination $hooks -Force
  $settingsPath = Join-Path $ClaudeHome 'settings.json'
  $settings = if (Test-Path -LiteralPath $settingsPath) { Get-Content -LiteralPath $settingsPath -Raw | ConvertFrom-Json -AsHashtable } else { [ordered]@{} }
  $command = 'pwsh -NoProfile -File ~/.claude/hooks/onesync-session.ps1'
  if ((Get-Content -LiteralPath $settingsPath -Raw -ErrorAction SilentlyContinue) -match [regex]::Escape('onesync-session.ps1')) {
    Write-Host 'The SessionStart hook is already in settings.json.'
    return
  }
  if (-not $settings.Contains('hooks')) { $settings['hooks'] = [ordered]@{} }
  if (-not $settings['hooks'].Contains('SessionStart')) { $settings['hooks']['SessionStart'] = @() }
  $settings['hooks']['SessionStart'] = @($settings['hooks']['SessionStart']) + @(@{ hooks = @(@{ type = 'command'; command = $command; timeout = 60 }) })
  [IO.File]::WriteAllText($settingsPath, ($settings | ConvertTo-Json -Depth 20), [Text.UTF8Encoding]::new($false))
  Write-Host 'Added the SessionStart hook to settings.json. Run "install-hook" once on each machine.'
}

function Install-Schedule {
  $script = $PSCommandPath
  $pwsh = (Get-Process -Id $PID).Path
  if (-not $IsWindows) {
    Write-Host 'Add this line with "crontab -e":'
    Write-Host "*/$EveryMinutes * * * * `"$pwsh`" -NoProfile -File `"$script`" sync >/dev/null 2>&1"
    return
  }
  # wscript runs pwsh with no window, so nothing flashes on the screen.
  $vbs = Join-Path $Repo 'tools/run-hidden.vbs'
  $action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument "`"$vbs`" `"$pwsh`" -NoProfile -File `"$script`" sync"
  $atLogon = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
  $repeat = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes $EveryMinutes)
  $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 15)
  Register-ScheduledTask -TaskName 'claude-onesync' -Action $action -Trigger $atLogon, $repeat -Settings $settings -Force | Out-Null
  Write-Host "Scheduled task 'claude-onesync' runs at logon and every $EveryMinutes minutes."
}

switch ($Command) {
  { $_ -in 'sync', 'status' } { Invoke-Sync }
  'install-hook' { Install-Hook }
  'install-schedule' { Install-Schedule }
  'uninstall-schedule' {
    if ($IsWindows) { Unregister-ScheduledTask -TaskName 'claude-onesync' -Confirm:$false; Write-Host 'Removed.' }
    else { Write-Host 'Remove the onesync line with "crontab -e".' }
  }
}
